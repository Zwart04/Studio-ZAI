"""Generate Android text styles from the core rendering catalog."""
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "core"))
from studiozai.pipeline.subtitle import PRESETS
mapping = {"outline_colour": "outlineColour", "border_style": "border", "margin_v": "marginV"}
rows = {key: {mapping.get(k, k): v for k, v in value.items()} for key, value in PRESETS.items()}
text = "// Generated by tools/sync_text_presets.py. Edit the core catalog first.\n"
text += "const creatorTextPresets = <String, Map<String, Object>>" + json.dumps(rows, ensure_ascii=False, indent=2) + ";\n"
(ROOT / "android/app/lib/services/text_presets.dart").write_text(text, encoding="utf-8")
print(f"Generated {len(rows)} templates")
