import 'dart:async';
import 'dart:math' as math;
import 'package:http/http.dart' as http;
import 'package:youtube_explode_dart/youtube_explode_dart.dart';

/// Public YouTube extraction. Each attempt has its own client so a timeout
/// closes its outstanding requests instead of leaving them running in the app.
class YoutubeSource {
  static Future<Map<String, dynamic>> captionMetadata(
      String url, String language) async {
    final youtube = YoutubeExplode();
    try {
      final video =
          await youtube.videos.get(url).timeout(const Duration(seconds: 20));
      final manifest = await youtube.videos.closedCaptions
          .getManifest(video.id)
          .timeout(const Duration(seconds: 20));
      final tracks = manifest.tracks
          .where((track) =>
              language == 'auto' ||
              track.language.code.split('-').first == language.split('-').first)
          .toList()
        ..sort((a, b) =>
            (a.isAutoGenerated ? 1 : 0).compareTo(b.isAutoGenerated ? 1 : 0));
      if (tracks.isEmpty) {
        throw StateError('Caption bahasa pilihan tidak tersedia');
      }
      final track = await youtube.videos.closedCaptions
          .get(tracks.first)
          .timeout(const Duration(seconds: 20));
      final duration = (video.duration?.inMilliseconds ?? 0) / 1000;
      final rows = track.captions
          .map((cue) => <String, dynamic>{
                'start': cue.offset.inMilliseconds / 1000,
                'end': (cue.offset + cue.duration).inMilliseconds / 1000,
                'text': cue.text,
                'words': <Map<String, dynamic>>[],
                'language': tracks.first.language.code,
              })
          .where((row) =>
              (row['end'] as double) > (row['start'] as double) &&
              '${row['text']}'.trim().isNotEmpty)
          .toList();
      if (rows.isEmpty ||
          rows.any((row) =>
              (row['start'] as double) < 0 ||
              (duration > 0 && (row['end'] as double) > duration + 2))) {
        throw StateError('Caption kosong atau timestamp tidak valid');
      }
      return {
        'title': video.title,
        'duration': duration,
        'language': tracks.first.language.code,
        'segments': rows
      };
    } finally {
      youtube.close();
    }
  }

  // Current public client profile also used by yt-dlp. Older Android profiles
  // can advertise URLs that stop transferring after the first few megabytes.
  static const vision = YoutubeApiClient({
    'context': {
      'client': {
        'clientName': 'VISIONOS',
        'clientVersion': '1.02',
        'deviceMake': 'Apple',
        'deviceModel': 'RealityDevice17,1',
        'userAgent':
            'Mozilla/5.0 (Macintosh; Intel Mac OS X 15_7_3) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/26.0 Safari/605.1.15',
        'osName': 'visionOS',
        'osVersion': '26.5.23O471',
        'hl': 'en',
        'gl': 'US',
      }
    }
  }, 'https://www.youtube.com/youtubei/v1/player?prettyPrint=false');

  /// Bounded HTTP ranges avoid the library's unbounded 403-refresh loop.
  /// Never replace a requested audio track with a different language.
  static Stream<List<int>> bytes(StreamInfo info,
      {http.Client? transport,
      Future<StreamManifest> Function(String)? refresh}) async* {
    final client = transport ?? http.Client();
    var offset = 0;
    var failures = 0;
    var current = info;
    try {
      while (offset < info.size.totalBytes) {
        final end = math.min(offset + 1024 * 1024, info.size.totalBytes) - 1;
        try {
          final request = http.Request('GET', current.url);
          request.headers['Range'] = 'bytes=$offset-$end';
          request.headers['User-Agent'] = current.url.queryParameters['c'] ==
                  'VISIONOS'
              ? vision.payload['context']['client']['userAgent'] as String
              : 'com.google.android.youtube/20.10.38 (Linux; U; Android 11) gzip';
          final response =
              await client.send(request).timeout(const Duration(seconds: 20));
          if (response.statusCode != 206 ||
              !('${response.headers['content-range']}')
                  .startsWith('bytes $offset-')) {
            await response.stream
                .timeout(const Duration(seconds: 20))
                .drain<void>();
            throw StateError(
                'YouTube menolak bagian unduhan (HTTP ${response.statusCode}).');
          }
          final before = offset;
          await for (final chunk
              in response.stream.timeout(const Duration(seconds: 20))) {
            offset += chunk.length;
            if (offset > end + 1) {
              throw StateError('Ukuran stream tidak sesuai.');
            }
            yield chunk;
          }
          if (offset == before) {
            throw StateError('YouTube mengirim bagian kosong.');
          }
          failures = 0;
        } catch (_) {
          if (++failures > 2) rethrow;
          final fresh = await (refresh ?? manifest)(info.videoId.value);
          current = fresh.streams.firstWhere((s) =>
              s.tag == info.tag &&
              (info is! AudioOnlyStreamInfo ||
                  (s is AudioOnlyStreamInfo &&
                      s.audioTrack?.id == info.audioTrack?.id)));
        }
      }
    } finally {
      client.close();
    }
  }

  static Future<StreamManifest> manifest(String url,
      {void Function(String)? onStatus}) async {
    Object? lastError;
    final clients = [vision, YoutubeApiClient.androidSdkless];
    for (var i = 0; i < clients.length; i++) {
      final youtube = YoutubeExplode();
      try {
        onStatus
            ?.call('Membaca stream YouTube · cara ${i + 1}/${clients.length}');
        return await youtube.videos.streamsClient
            .getManifest(
              url,
              ytClients: [clients[i]],
              requireWatchPage: clients[i] == vision,
            )
            .timeout(const Duration(seconds: 25));
      } catch (error) {
        lastError = error;
      } finally {
        youtube.close();
      }
    }
    throw StateError('YouTube belum menyediakan stream yang dapat diunduh. '
        'Coba jaringan lain atau pilih berkas video dari perangkat. '
        'Video privat, dibatasi usia, atau dibatasi wilayah tidak didukung. '
        'Detail: $lastError');
  }

  static VideoOnlyStreamInfo video(StreamManifest manifest,
      {int maxHeight = 720}) {
    final choices = manifest.videoOnly
        .where((s) =>
            s.videoResolution.height <= maxHeight &&
            s.videoCodec.startsWith('avc1'))
        .toList()
      ..sort((a, b) {
        final resolution =
            b.videoResolution.height.compareTo(a.videoResolution.height);
        return resolution != 0
            ? resolution
            : b.bitrate.bitsPerSecond.compareTo(a.bitrate.bitsPerSecond);
      });
    if (choices.isEmpty) {
      throw StateError(
          'Video H.264 hingga ${maxHeight}p tidak tersedia. Pilih berkas video dari perangkat.');
    }
    return choices.first;
  }

  static AudioOnlyStreamInfo audio(StreamManifest manifest, String? language) {
    final choices = manifest.audioOnly
        .where((s) => language == null
            ? (s.audioTrack == null || s.audioTrack!.audioIsDefault)
            : (s.audioTrack?.id ?? '')
                    .toLowerCase()
                    .split(RegExp(r'[-_.]'))
                    .first ==
                language.toLowerCase())
        .toList()
      ..sort(
          (a, b) => b.bitrate.bitsPerSecond.compareTo(a.bitrate.bitsPerSecond));
    if (choices.isEmpty) {
      throw StateError(
          'Track audio ${language ?? "bawaan"} tidak tersedia. Pilih track lain.');
    }
    return choices.first;
  }

  /// URL playlist HLS (m3u8) untuk satu video, atau null bila tidak tersedia.
  /// HLS terdiri dari segmen yang dapat di-address secara individu, sehingga
  /// hanya rentang waktu yang dipilih yang perlu diunduh (bukan seluruh stream).
  static String? hlsPlaylistUrl(StreamManifest manifest) {
    final hls = manifest.hls.whereType<HlsMuxedStreamInfo>().toList();
    if (hls.isEmpty) return null;
    final ok = hls.where((h) => h.videoResolution.height <= 720).toList();
    final chosen = (ok.isNotEmpty ? ok : hls)
      ..sort((a, b) =>
          b.videoResolution.height.compareTo(a.videoResolution.height));
    return chosen.first.url.toString();
  }

  /// User-Agent yang tidak di-throttle oleh CDN YouTube untuk range request.
  static String rangeUserAgent(Uri uri) {
    if (uri.queryParameters['c'] == 'VISIONOS') {
      return vision.payload['context']['client']['userAgent'] as String;
    }
    return 'com.google.android.youtube/20.10.38 '
        '(Linux; U; Android 11; SMP_BUILD SGP; wv) gzip';
  }
}
